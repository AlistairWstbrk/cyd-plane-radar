#!/usr/bin/env python3
"""Build the on-device airport search index from OurAirports.

Every large and medium airport plus small airports with scheduled service,
with ICAO/GPS ident, IATA code, a shortened name, city and region, so the
radar can search by name ("tampa"), city, ICAO ("KTPA") or IATA ("TPA")
without a network connection.

Usage: python scripts/build_airport_index.py [airports.csv]
(downloads airports.csv when no path is given and sim/sim_data has none)
"""
from __future__ import annotations

import csv
import io
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_H = ROOT / "include" / "data" / "airport_index.h"
OUT_CPP = ROOT / "src" / "data" / "airport_index_data.cpp"
URL = "https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv"

ABBREV = [
    (r"\bInternational\b", "Intl"),
    (r"\bRegional\b", "Rgnl"),
    (r"\bMunicipal\b", "Muni"),
    (r"\bAirport\b", ""),
    (r"\bAirfield\b", "Afld"),
    (r"\bAir Base\b", "AB"),
    (r"\bAir Force Base\b", "AFB"),
    (r"\bAeroporto\b", ""),
    (r"\bAeropuerto\b", ""),
    (r"\bAéroport\b", ""),
    (r"\bFlughafen\b", ""),
    (r"\bCounty\b", "Co"),
    (r"\bSaint\b", "St"),
    (r"\bMount\b", "Mt"),
]
TYPES = {"large_airport": 2, "medium_airport": 1, "small_airport": 0}


def ascii_fold(s: str) -> str:
    import unicodedata
    s = s.replace("\u2013", "-").replace("\u2014", "-").replace("\u2019", "'")
    s = unicodedata.normalize("NFKD", s)
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    s = s.replace("ß", "ss").replace("ø", "o").replace("Ø", "O").replace("ł", "l").replace("Ł", "L")
    s = s.replace("æ", "ae").replace("Æ", "AE").replace("đ", "d").replace("Đ", "D")
    return "".join(ch if 32 <= ord(ch) < 127 else "" for ch in s)


def shorten(name: str) -> str:
    n = name
    for pat, rep in ABBREV:
        n2 = re.sub(pat, rep, n)
        if n2.strip():
            n = n2
    n = re.sub(r"\s*[-/,]\s*$", "", re.sub(r"\s+", " ", n)).strip(" -,/")
    n = re.sub(r"\(\s*\)", "", n).strip()
    return ascii_fold(n)[:34].strip()


def c_str(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def load(path: str | None) -> list[dict[str, str]]:
    local = Path(path) if path else ROOT / "sim" / "sim_data" / "airports.csv"
    if local.exists():
        return list(csv.DictReader(open(local, encoding="utf-8")))
    with urllib.request.urlopen(URL, timeout=60) as resp:
        return list(csv.DictReader(io.StringIO(resp.read().decode("utf-8"))))


def main() -> int:
    rows = load(sys.argv[1] if len(sys.argv) > 1 else None)
    out = []
    for a in rows:
        t = a["type"]
        if t not in TYPES:
            continue
        if t == "small_airport" and not (a["scheduled_service"] == "yes" and a["iata_code"]):
            continue
        ident = a["ident"].strip().upper()
        if not ident or len(ident) > 7:
            continue
        try:
            lat = int(round(float(a["latitude_deg"]) * 1e5))
            lon = int(round(float(a["longitude_deg"]) * 1e5))
        except ValueError:
            continue
        iata = a["iata_code"].strip().upper()[:3]
        name = shorten(a["name"]) or ident
        city = re.sub(r"\s*\(.*$", "", ascii_fold(a["municipality"])).strip()[:22]
        if city and city.lower() in name.lower():
            city = ""
        region = a["iso_region"].strip()
        if region.endswith("-U-A") or region.count("-") != 1:
            region = a["iso_country"].strip()
        region = region[:6]
        kind = TYPES[t] | (4 if a["scheduled_service"] == "yes" else 0)
        out.append((ident, iata, kind, lat, lon, f'"{c_str(name)}" "\\0" "{c_str(city)}" "\\0" "{region}"', name))
    out.sort(key=lambda r: r[0])

    text_bytes = sum(len(r[6]) + 30 for r in out)
    OUT_H.write_text(
        "\n".join([
            "// Generated by scripts/build_airport_index.py - do not edit.",
            "#pragma once",
            "",
            "#include <cstddef>",
            "#include <cstdint>",
            "",
            "namespace data::airport_index {",
            "",
            "/** kind: bits 0-1 size (0 small, 1 medium, 2 large), bit 2 scheduled service. */",
            "struct Entry {",
            "  char ident[8];",
            "  char iata[4];",
            "  uint8_t kind;",
            "  int32_t lat_e5;",
            "  int32_t lon_e5;",
            "  const char* text;  // \"Name\\0City\\0Region\" (city may be empty)",
            "};",
            "",
            f"constexpr size_t kCount = {len(out)};",
            "extern const Entry kEntries[];  // sorted by ident",
            "",
            "}  // namespace data::airport_index",
            "",
        ]),
        encoding="utf-8",
    )
    lines = [
        "// Generated by scripts/build_airport_index.py - do not edit.",
        "// Data: OurAirports (public domain).",
        '#include "data/airport_index.h"',
        "",
        "namespace data::airport_index {",
        "",
        "const Entry kEntries[] = {",
    ]
    for ident, iata, kind, lat, lon, text, _ in out:
        lines.append(f'  {{"{ident}", "{iata}", {kind}, {lat}, {lon}, {text}}},')
    lines += ["};", "", "}  // namespace data::airport_index", ""]
    OUT_CPP.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(out)} airports, ~{(len(out) * 24 + text_bytes) // 1024} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
